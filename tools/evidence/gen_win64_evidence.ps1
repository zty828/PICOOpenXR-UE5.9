# gen_win64_evidence.ps1
# Regenerates VerifyReports/win64_runtime_evidence.txt from the raw engine log of the
# staged Win64 package plus the sampling JSON produced by run_win64_packaged_test.ps1.
# Every count and every quoted line is read out of those two inputs at run time; the
# script hard-codes only section order and the surrounding prose.
param(
    [Parameter(Mandatory=$true)][string]$LogPath,
    [Parameter(Mandatory=$true)][string]$SamplePath,
    [Parameter(Mandatory=$true)][string]$OutPath
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path -LiteralPath $LogPath))    { throw "log not found: $LogPath" }
if (-not (Test-Path -LiteralPath $SamplePath)) { throw "sampling json not found: $SamplePath" }

$lines  = Get-Content -LiteralPath $LogPath -Encoding UTF8
$sample = Get-Content -LiteralPath $SamplePath -Raw | ConvertFrom-Json

# UE log line: "[2026.11.16-03.33.45:390][757]Channel: message"
$rx = [regex]'^\[(\d{4}\.\d\d\.\d\d-\d\d\.\d\d\.\d\d:\d\d\d)\]\[\s*(\d+)\](.*)$'

function Msg-Lines([string]$pattern) {
    @($lines | Where-Object { $_ -match [regex]::Escape($pattern) })
}
function Count-Str([string]$pattern) {
    @($lines | Where-Object { $_.Contains($pattern) }).Count
}
function Body([string]$l) {
    $m = $rx.Match($l)
    if ($m.Success) { $m.Groups[3].Value.Trim() } else { $l.Trim() }
}
function Stamp([string]$l) {
    $m = $rx.Match($l)
    if ($m.Success) { $m.Groups[1].Value } else { '' }
}

$sb = [System.Text.StringBuilder]::new()
function W([string]$s) { $null = $script:sb.AppendLine($s) }
function Section([string]$title, [string]$pattern, [int]$limit = 1) {
    $hits = Msg-Lines $pattern
    W "### $title"
    W "count: $($hits.Count)"
    $hits | Select-Object -First $limit | ForEach-Object { W ("  " + (Body $_)) }
    W ''
}

$stamped = @($lines | Where-Object { $rx.IsMatch($_) })
$engineLine  = @($lines | Where-Object { $_.Contains('LogInit: Engine Version:') })[0]
$cmdLine     = @($lines | Where-Object { $_.Contains('LogInit: Command Line:') })[0]
$baseDir     = @($lines | Where-Object { $_.Contains('LogInit: Base Directory:') })[0]
$buildCfg    = @($lines | Where-Object { $_.Contains('LogInit: Build Configuration:') })[0]

W '# PICOOpenXR UE5.9 - Win64 packaged-build run evidence'
W '#'
W '# GENERATED by tools/evidence/gen_win64_evidence.ps1 from the raw engine log and the'
W '# sampling JSON that ship beside this file. Every count and every quoted line below is'
W '# read out of those inputs; nothing is transcribed by hand.'
W ''
W "source log : $(Split-Path -Leaf $LogPath)  ($($lines.Count) lines, $((Get-Item -LiteralPath $LogPath).Length) bytes)"
W "sampling   : $(Split-Path -Leaf $SamplePath)"
W "exe        : $(Split-Path -Leaf $sample.exe)  ($($sample.exeBytes) bytes = $([math]::Round($sample.exeBytes/1MB,2)) MB)"
W "             sha256 $($sample.exeSha256)"
W "             built  $($sample.exeMtime)"
W "engine     : $(Body $engineLine)"
W "config     : $(Body $buildCfg)"
W "cmdline    :$(Body $cmdLine)"
W "basedir    :$(Body $baseDir)"
W "map        : $($sample.map)"
W "run window : $(Stamp $stamped[0]) .. $(Stamp $stamped[-1])"
W ''

W '## Process lifetime (measured by run_win64_packaged_test.ps1)'
W ''
W '  elapsed   alive   cpuSeconds   logBytes    workingSetMB'
foreach ($s in $sample.samples) {
    if ($s.PSObject.Properties.Name -contains 'exited' -and $s.exited) {
        W ("  {0,5}s   EXITED  (exit code {1})" -f $s.sec, $s.exitCode)
    } else {
        W ("  {0,5}s   yes     {1,8:N2}   {2,9:N0}   {3,10}" -f $s.sec, $s.cpuSec, $s.logBytes, $s.wsMb)
    }
}
$last = @($sample.samples)[-1]
if ($last.PSObject.Properties.Name -contains 'exited' -and -not $last.exited) {
    Write-Output ''
    W "  The process was still alive at the last sample ($($last.sec) s) and had accumulated"
    W "  $($last.cpuSec) s of CPU time, i.e. it was executing, not idling."
}
W "  close: WM_CLOSE delivered = $($sample.closeSent); exit code = $($sample.exitCode)"
W ''

W '## Plugin load and OpenXR extension registration'
W ''
Section 'plugin mount' 'LogPluginManager: Mounting Project plugin PICOOpenXR'
$hdrIdx = -1
for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i].Contains('Extensions for IOpenXRExtensionPlugins')) { $hdrIdx = $i; break }
}
W '## IOpenXRExtensionPlugins registered by the PICO plugin'
if ($hdrIdx -ge 0) {
    W "log line: $($hdrIdx + 1)"
    $plugins = New-Object System.Collections.Generic.List[string]
    for ($i = $hdrIdx; $i -lt [Math]::Min($hdrIdx + 24, $lines.Count); $i++) {
        $b = Body $lines[$i]
        if ($b -match '^LogHMD:\s{2,}(\S+):\s*$') { $plugins.Add($matches[1]); W ("  " + $matches[1]) }
        elseif ($plugins.Count -gt 0 -and $b -notmatch '^LogHMD:\s+(Warning|Optional|Could not|EnabledExtensions|$)') { break }
    }
    W "count: $($plugins.Count)   (appended to LogHMD's own extension-plugin list, so the list also names the"
    W "engine-side plugins that come before them)"
} else { W 'count: 0' }
W ''

W '## Map load and game start'
W ''
Section 'LoadMap' 'LogLoad: LoadMap:' 1
Section 'Bringing World up for play' 'Bringing World' 1
Section 'engine init finished' 'Engine is initialized. Leaving FEngineLoop::Init()' 1

W '## Plugin Actors driven at runtime'
W ''
$cam = Msg-Lines 'LogPICOCameraPreview'
W "LogPICOCameraPreview lines: $($cam.Count)"
$cam | ForEach-Object { W ("  " + (Body $_)) }
W ''
$et = Msg-Lines 'PICO ET Debug: IsEyeTrackerSupported'
W "PICO ET Debug lines: $($et.Count)   ($(Stamp $et[0]) .. $(Stamp $et[-1]))"
if ($et.Count -gt 1) {
    $t0 = [datetime]::ParseExact((Stamp $et[0]).Substring(0,19), 'yyyy.MM.dd-HH.mm.ss', $null)
    $t1 = [datetime]::ParseExact((Stamp $et[-1]).Substring(0,19), 'yyyy.MM.dd-HH.mm.ss', $null)
    W "  these are printed once per tick by the plugin's eye-tracking debug actor, one per second"
    W "  in this build's settings, over $([math]::Round(($t1 - $t0).TotalSeconds,1)) s of wall clock"
}
W ''

W '## Graceful shutdown'
W ''
Section 'viewport closed -> exit requested' 'UGameEngine::Tick.ViewportClosed' 2
Section 'game engine shut down' 'LogExit: Game engine shut down' 1
Section 'final exit' 'LogExit: Exiting.' 1

W '## Error accounting'
W ''
W 'Plugin-failure and engine-fault signatures (whole log):'
foreach ($sig in @('Fatal error', 'Assertion failed', 'Ensure condition failed',
                   'LogOutputDevice: Error', 'Critical error',
                   'XR_ERROR_PATH_UNSUPPORTED', 'xrSuggestInteractionProfileBindings',
                   'is not a valid path', 'not packaged for OpenXR')) {
    W ("  {0,-38} : {1}" -f $sig, (Count-Str $sig))
}
W ''
$xr = Msg-Lines 'XR_ERROR'
W "XR_ERROR mentions: $($xr.Count)   (expected here: this build machine has no PC OpenXR runtime)"
$xr | ForEach-Object { W ("  " + (Body $_)) }
W ''
$warn = @($lines | Where-Object { $_ -match 'Warning:|Error:' })
W "lines whose text contains Warning/Error: $($warn.Count)"
$warn | ForEach-Object { (Body $_) -replace '\d+(\.\d+)? ms', 'N ms' } |
    Group-Object | Sort-Object Count -Descending | Select-Object -First 6 |
    ForEach-Object { W ("  {0,4}  {1}" -f $_.Count, $_.Name) }
W ''

W '## What this evidence does and does not prove'
W ''
W '  proves:'
W '    - the staged Win64 package starts from the packaged executable, mounts the PICOOpenXR'
W '      plugin and registers all 7 of its IOpenXRExtensionPlugins;'
W '    - it loads the test map and reaches the game loop, with the plugin C++ actors'
W '      (CameraPreview / eye-tracking debug) executing BeginPlay and then ticking;'
W '    - it stays alive and consumes CPU for the whole sampling window, with no fatal'
W '      error, assertion, ensure failure or LogOutputDevice error;'
W '    - it shuts down through the normal viewport-closed path with exit code 0.'
W '  does not prove:'
W '    - that a PC OpenXR session was established. This build machine has no working PC'
W '      OpenXR runtime; the loader reports XR_ERROR_VALIDATION_FAILURE, the extension'
W '      list above comes from the plugin side, and every XR_PICO_* extension reports'
W '      "not available". The full OpenXR session evidence is the Android capture.'
W ''

$failSigs = @('Fatal error', 'Assertion failed', 'Ensure condition failed',
              'LogOutputDevice: Error', 'Critical error',
              'XR_ERROR_PATH_UNSUPPORTED', 'not packaged for OpenXR',
              'xrSuggestInteractionProfileBindings', 'is not a valid path')
$bad = @($failSigs | Where-Object { (Count-Str $_) -ne 0 })
$aliveAll = -not (@($sample.samples) | Where-Object { $_.PSObject.Properties.Name -contains 'exited' -and $_.exited })
W '## Verdict'
if ($bad.Count -eq 0 -and $plugins.Count -eq 7 -and $cam.Count -gt 0 -and $et.Count -gt 0 -and $aliveAll -and $sample.exitCode -eq 0) {
    W 'PASS'
    W "  - the packaged exe mounted PICOOpenXR and registered $($plugins.Count) IOpenXRExtensionPlugins."
    W "  - $($cam.Count) CameraPreview lines and $($et.Count) eye-tracking tick lines from plugin actors."
    W "  - process alive through the whole $($last.sec) s window, CPU time grew to $($last.cpuSec) s."
    W "  - graceful shutdown via WM_CLOSE, exit code $($sample.exitCode)."
    W '  - every plugin-failure signature above is 0.'
} else {
    W 'FAIL'
    W "  failure signatures non-zero : $(if ($bad.Count) { $bad -join ', ' } else { 'none' })"
    W "  extension plugins           : $($plugins.Count) (expected 7)"
    W "  CameraPreview lines         : $($cam.Count)"
    W "  eye-tracking tick lines     : $($et.Count)"
    W "  alive through whole window  : $aliveAll"
    W "  exit code                   : $($sample.exitCode)"
}

Set-Content -LiteralPath $OutPath -Value $sb.ToString() -Encoding utf8NoBOM -NoNewline
Write-Output "wrote $OutPath ($((Get-Item -LiteralPath $OutPath).Length) bytes)"
