# gen_android_evidence.ps1
# Regenerates VerifyReports/android_runtime_evidence.txt from a raw adb logcat capture.
# Every count and every quoted line is taken from that capture at run time; the script
# hard-codes only section order and the surrounding prose.
param(
    [Parameter(Mandatory=$true)][string]$LogPath,
    [Parameter(Mandatory=$true)][string]$ApkPath,
    [Parameter(Mandatory=$true)][string]$OutPath,
    [string]$AppPid = '3647'
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path -LiteralPath $LogPath)) { throw "log not found: $LogPath" }
if (-not (Test-Path -LiteralPath $ApkPath)) { throw "apk not found: $ApkPath" }

$lines = Get-Content -LiteralPath $LogPath -Encoding UTF8
$apk   = Get-Item -LiteralPath $ApkPath

# logcat line: "MM-DD hh:mm:ss.fff L/TAG( PID): message"
$rx = [regex]'^\d\d-\d\d\s+\d\d:\d\d:\d\d\.\d+\s+([VDIWEF])/([^(]+)\(\s*(\d+)\):\s?(.*)$'

function Parse-All {
    $out = New-Object System.Collections.Generic.List[object]
    foreach ($l in $lines) {
        $m = $rx.Match($l)
        if ($m.Success) {
            $out.Add([pscustomobject]@{
                Level = $m.Groups[1].Value
                Tag   = $m.Groups[2].Value.Trim()
                Pid   = $m.Groups[3].Value
                Msg   = $m.Groups[4].Value
                Raw   = $l
            })
        }
    }
    ,$out
}
$rec = Parse-All

function Count-Msg([string]$pattern) {
    @($rec | Where-Object { $_.Msg.Contains($pattern) }).Count
}
function Msg-Lines([string]$pattern) {
    @($rec | Where-Object { $_.Msg.Contains($pattern) })
}
function Count-Raw([string]$pattern) {
    @($lines | Select-String -SimpleMatch $pattern).Count
}

$sb = [System.Text.StringBuilder]::new()
function W([string]$s) { $null = $script:sb.AppendLine($s) }

function Section([string]$title, [string]$pattern, [int]$limit = 1) {
    $hits = Msg-Lines $pattern
    W "## $title"
    W "count: $($hits.Count)"
    $hits | Select-Object -First $limit | ForEach-Object { W ("  " + $_.Msg) }
    W ""
}

$engineVersion = (Msg-Lines 'LogInit: Engine Version:')[0].Msg
$osLine        = (Msg-Lines 'LogAndroid: Display: Android Version:')[0].Msg
$cmdLine       = (Msg-Lines 'LogInit: Command Line:')[0].Msg

W '# PICOOpenXR UE5.9 - Android Runtime Evidence (PICO OS emulator, launched with -vr)'
W '#'
W '# GENERATED by tools/evidence/gen_android_evidence.ps1 from the raw logcat capture that ships'
W '# beside this file. Every count and every quoted line below is read out of that capture;'
W '# nothing is transcribed by hand.'
W ''
W "source log : $(Split-Path -Leaf $LogPath)  ($($lines.Count) lines, $((Get-Item -LiteralPath $LogPath).Length) bytes)"
W "apk        : $(Split-Path -Leaf $ApkPath)  ($($apk.Length) bytes = $([math]::Round($apk.Length/1MB,2)) MB)"
W "engine     : $engineVersion"
W "os         : $osLine"
W "cmdline    :$cmdLine"
W "capture    : $($lines[0])"
W "           : ..."
W "           : $($lines[$lines.Count-1])"
W ''

W '## Launch'
W ''
Section 'adb am start command line override' 'adb am start command line override'
Section 'OpenXRImmersiveHMD' 'OpenXR_APL Found OpenXRImmersiveHMD mode'
Section 'packaged for Android OpenXR' 'App is packaged for Android OpenXR'

W '## OpenXR initialisation'
W ''
Section 'CustomLoader from plugin HMDPICO' 'CustomLoader from plugin HMDPICO'
Section 'Loaded PICO OpenXR Loader' 'Loaded PICO OpenXR Loader'
Section 'PICO OpenXR API layer enabled' 'PICO OpenXR API layer enabled'
Section 'pvr.sdk.version' 'pvr.sdk.version'
Section 'xrCreateInstance succeeded' 'xrCreateInstance succeeded'
Section 'Initialized OpenXR on Pico XRRuntime' 'Initialized OpenXR on Pico XRRuntime'
Section 'IOpenXRExtensionPlugin API layer enabled' 'IOpenXRExtensionPlugin API layer enabled'
Section 'Mobile Multiview' 'Mobile Multiview is Enabled'

W '## Extension plugin registration'
$hdr = @($rec | Where-Object { $_.Msg.Contains('Extensions for IOpenXRExtensionPlugins') })
if ($hdr.Count -gt 0) {
    $hdrRec = $hdr[0]
    $i0 = [array]::IndexOf($lines, $hdrRec.Raw)
    W "log line: $($i0 + 1)"
    $plugins = New-Object System.Collections.Generic.List[string]
    for ($i = $i0; $i -lt [Math]::Min($i0 + 12, $lines.Count); $i++) {
        $m = $rx.Match($lines[$i])
        if (-not $m.Success) { continue }
        $body = $m.Groups[4].Value
        if ($body -match 'LogHMD:\s+(\S+):') {
            $plugins.Add($matches[1])
            W ("  " + $matches[1])
        } elseif ($plugins.Count -gt 0) { break }
    }
    W "count: $($plugins.Count)"
} else { W 'count: 0' }
W ''

W '## Optional extensions reported not available'
$optLines = @(Msg-Lines 'Optional extension')
W "count: $($optLines.Count)"
$optLines | ForEach-Object {
    $ext = if ($_.Msg -match 'Optional extension (\S+) is not available') { $matches[1] } else { $_.Msg }
    W ("  " + $ext)
}
W ''

W '## RHI / swapchain'
W ''
Section 'PICO disable RHI thread requested' 'PICO disable RHI thread requested'
Section 'Swapchain format not supported' 'Swapchain format not supported'
Section 'PICO VRS format' 'PICO VRS format current cvar value'

W '## XR session state changed'
$st = Msg-Lines 'XR session state changed'
W "count: $($st.Count)"
$st | ForEach-Object { W ("  " + $_.Msg) }
W ''

W '## Input / haptics'
W ''
Section 'XR_EXT_haptic_parametric extension loaded' 'XR_EXT_haptic_parametric extension loaded'
Section 'Created vibration actions for parametric haptics' 'Created vibration actions for parametric haptics'
Section 'Skipping haptic bindings' 'Skipping haptic bindings'
Section 'parametric haptic properties' 'parametric haptic properties' 2

W '## Frame submission (PxrMetric)'
$appMetrics = @($rec | Where-Object { $_.Msg.StartsWith('FPS=') -and $_.Msg.Contains('Pkg=com.YourCompany.PICOHost59') })
$allMetrics = @($rec | Where-Object { $_.Msg.StartsWith('FPS=') -and $_.Msg.Contains('Pkg=') })
W "app frames sampled: $($appMetrics.Count)   (all PxrMetric lines in capture: $($allMetrics.Count);"
W "the remainder belong to the launcher and the spatial runtime)"
if ($appMetrics.Count -gt 0) {
    $firstId = if ($appMetrics[0].Msg -match 'FrmId=(\d+)') { $matches[1] } else { '?' }
    $lastId  = if ($appMetrics[$appMetrics.Count-1].Msg -match 'FrmId=(\d+)') { $matches[1] } else { '?' }
    W "frame id range: $firstId .. $lastId"
    W 'last 8:'
    $appMetrics | Select-Object -Last 8 | ForEach-Object { W ('  ' + $_.Msg) }
}
W ''

W '## Error accounting'
W ''
$ue = @($rec | Where-Object { $_.Tag -eq 'UE' })
$ueBad = @($ue | Where-Object { $_.Level -ne 'D' -and $_.Level -ne 'I' })
$ueWarn = @($ue | Where-Object { $_.Msg -match 'Warning:|Error:|Deprecated' })
W "UE log lines in capture                  : $($ue.Count)"
W "UE lines at W/E/F severity               : $($ueBad.Count)"
W "UE lines whose text contains Warning/Error: $($ueWarn.Count)"
W ''
W 'Plugin-failure signatures (whole capture, any tag):'
foreach ($sig in @('LogOutputDevice: Error', 'Ensure condition failed', 'Assertion failed',
                   'Critical error', 'Fatal error', 'XR_ERROR_PATH_UNSUPPORTED',
                   'xrSuggestInteractionProfileBindings', 'is not a valid path',
                   'not packaged for OpenXR')) {
    W ("  {0,-36} : {1}" -f $sig, (Count-Raw $sig))
}
W ''

W '### Platform-side error lines (emulator image services, not the plugin)'
$appRec = @($rec | Where-Object { $_.Pid -eq $AppPid })
$appErr = @($appRec | Where-Object { $_.Level -eq 'E' })
W "app process ($AppPid) lines : $($appRec.Count)"
W "app process E/ lines  : $($appErr.Count)"
W ''
W 'by tag:'
$appErr | Group-Object Tag | Sort-Object Count -Descending | Select-Object -First 12 |
    ForEach-Object { W ("  {0,6}  {1}" -f $_.Count, $_.Name) }
W ''
W 'most frequent messages:'
$appErr | Group-Object Msg | Sort-Object Count -Descending | Select-Object -First 8 |
    ForEach-Object { W ("  {0,6}  {1}" -f $_.Count, $_.Name) }
W ''

W '## Verdict'
$failSigs = @('XR_ERROR_PATH_UNSUPPORTED', 'Ensure condition failed', 'LogOutputDevice: Error',
              'not packaged for OpenXR', 'Fatal error', 'Assertion failed', 'Critical error')
$bad = @($failSigs | Where-Object { (Count-Raw $_) -ne 0 })
$pluginCount = if ($null -ne $plugins) { $plugins.Count } else { 0 }
if ($bad.Count -eq 0 -and $pluginCount -eq 7 -and $st.Count -eq 5 -and $appMetrics.Count -gt 0) {
    W 'PASS'
    W "  - OpenXR instance created against the PICO runtime (xrCreateInstance succeeded, API version 1.1)."
    W "  - $pluginCount IOpenXRExtensionPlugins registered."
    W "  - XR session walked the full state chain, $($st.Count) transitions ending FOCUSED."
    W "  - $($appMetrics.Count) frame-submission samples from the app process."
    W "  - every plugin-failure signature above is 0."
} else {
    W 'FAIL'
    W "  failure signatures non-zero : $(if ($bad.Count) { $bad -join ', ' } else { 'none' })"
    W "  extension plugins registered : $pluginCount (expected 7)"
    W "  session state transitions    : $($st.Count) (expected 5)"
    W "  app frame samples            : $($appMetrics.Count)"
}

Set-Content -LiteralPath $OutPath -Value $sb.ToString() -Encoding utf8NoBOM -NoNewline
Write-Output "wrote $OutPath ($((Get-Item -LiteralPath $OutPath).Length) bytes)"
